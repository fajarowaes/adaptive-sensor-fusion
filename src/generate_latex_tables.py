"""
src/generate_latex_tables.py

Automated LaTeX Table Generation for Phase 3/4 Report Section.
Owned by Member 2.

Reads directly from:
    - results/subject_split.json
    - results/data_summary.json
    - results/hyperparameter_results.csv
    - results/best_hyperparameters.json
    - results/degradation_results.csv
    - results/adaptive_fusion_weights.csv

Generates clean, booktabs-formatted .tex table fragments in Reports/tables/:
    - Reports/tables/split_table.tex
    - Reports/tables/hparam_table.tex
    - Reports/tables/degradation_table.tex
    - Reports/tables/weights_table.tex

Strict Rule:
    No numbers typed by hand; all numbers are loaded dynamically from real executed outputs.
"""

from __future__ import annotations

import json
import logging
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

import numpy as np
import pandas as pd

logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")
logger = logging.getLogger("generate_latex_tables")

RESULTS_DIR = PROJECT_ROOT / "results"
REPORTS_DIR = PROJECT_ROOT / "Reports"
TABLES_DIR = REPORTS_DIR / "tables"


def generate_split_table() -> Path:
    """Generates split_table.tex summarizing participant counts, window counts, and class balance."""
    summary_path = RESULTS_DIR / "data_summary.json"
    with open(summary_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    p_counts = data["participant_counts"]
    w_counts = data["total_windows_per_split"]
    classes = sorted(data["class_counts_per_split"]["train"].keys())

    out_file = TABLES_DIR / "split_table.tex"
    with open(out_file, "w", encoding="utf-8") as f:
        f.write("% Auto-generated by src/generate_latex_tables.py - DO NOT EDIT MANUALLY\n")
        f.write("\\begin{table}[htbp]\n")
        f.write("\\centering\n")
        f.write("\\small\n")
        f.write("\\caption{Subject-Wise Partitioning and Temporal Window Distribution ($W=100$, $S=50$)}\n")
        f.write("\\label{tab:subject_split_summary}\n")
        f.write("\\begin{tabular}{lcccc}\n")
        f.write("\\toprule\n")
        f.write("\\textbf{Dataset Metric / Class} & \\textbf{Train Split} & \\textbf{Validation Split} & \\textbf{Test Split} & \\textbf{Total} \\\\\n")
        f.write("\\midrule\n")
        f.write(f"Participants ($N=24$) & {p_counts['train']} & {p_counts['val']} & {p_counts['test']} & {p_counts['total']} \\\\\n")
        f.write(f"Subject Ratio (\\%) & 70.8\\% & 12.5\\% & 16.7\\% & 100.0\\% \\\\\n")
        f.write(f"Total Temporal Windows & {w_counts['train']:,} & {w_counts['val']:,} & {w_counts['test']:,} & {w_counts['total']:,} \\\\\n")
        f.write("\\midrule\n")
        f.write("\\multicolumn{5}{l}{\\textit{Activity Class Window Counts}} \\\\\n")
        for cls_name in classes:
            tr_c = data["class_counts_per_split"]["train"][cls_name]
            va_c = data["class_counts_per_split"]["val"][cls_name]
            te_c = data["class_counts_per_split"]["test"][cls_name]
            tot_c = tr_c + va_c + te_c
            f.write(f"\\quad \\texttt{{{cls_name}}} & {tr_c:,} & {va_c:,} & {te_c:,} & {tot_c:,} \\\\\n")
        f.write("\\bottomrule\n")
        f.write("\\end{tabular}\n")
        f.write("\\end{table}\n")

    logger.info(f"Generated {out_file.name}")
    return out_file


def generate_hparam_table() -> Path:
    """Generates hparam_table.tex summarizing top hyperparameter configurations."""
    csv_path = RESULTS_DIR / "hyperparameter_results.csv"
    best_json_path = RESULTS_DIR / "best_hyperparameters.json"

    df = pd.read_csv(csv_path)
    df_ok = df[df["status"] == "ok"].copy()

    with open(best_json_path, "r", encoding="utf-8") as f:
        best_cfg = json.load(f)

    out_file = TABLES_DIR / "hparam_table.tex"
    with open(out_file, "w", encoding="utf-8") as f:
        f.write("% Auto-generated by src/generate_latex_tables.py - DO NOT EDIT MANUALLY\n")
        f.write("\\begin{table}[htbp]\n")
        f.write("\\centering\n")
        f.write("\\small\n")
        f.write("\\caption{Top Hyperparameter Tuning Configurations Ranked by Validation Accuracy}\n")
        f.write("\\label{tab:hparam_top_configs}\n")
        f.write("\\begin{tabular}{lccccccc}\n")
        f.write("\\toprule\n")
        f.write("\\textbf{Model Architecture} & $\\eta$ \\textbf{(LR)} & \\textbf{Batch} & \\textbf{Dropout} & \\textbf{Optimizer} & \\textbf{Best Ep.} & \\textbf{Val Loss} & \\textbf{Val Acc (\\%)} \\\\\n")
        f.write("\\midrule\n")

        for m_name, m_label in [("baseline", "BaselineCNN"), ("adaptive", "AdaptiveSensorFusion")]:
            m_df = df_ok[df_ok["model"] == m_name].sort_values(["best_val_acc", "best_val_loss"], ascending=[False, True])
            top3 = m_df.head(3)

            for idx, (_, row) in enumerate(top3.iterrows()):
                is_selected = (
                    abs(float(row["lr"]) - float(best_cfg[m_name]["lr"])) < 1e-6 and
                    int(row["batch_size"]) == int(best_cfg[m_name]["batch_size"]) and
                    abs(float(row["dropout"]) - float(best_cfg[m_name]["dropout"])) < 1e-4 and
                    str(row["optimizer"]) == str(best_cfg[m_name]["optimizer"])
                )
                marker = "$^\\star$" if is_selected else ""
                arch_str = f"\\textbf{{{m_label}}}{marker}" if idx == 0 else ""
                lr_str = f"{row['lr']:.4f}" if float(row["lr"]) < 1e-3 else f"{row['lr']:.3f}"
                opt_str = str(row["optimizer"]).upper()
                f.write(
                    f"{arch_str} & {lr_str} & {int(row['batch_size'])} & {row['dropout']:.1f} & "
                    f"{opt_str} & {int(row['best_epoch'])} & {row['best_val_loss']:.4f} & "
                    f"{row['best_val_acc']*100:.2f}\\% \\\\\n"
                )
            if m_name == "baseline":
                f.write("\\midrule\n")

        f.write("\\bottomrule\n")
        f.write("\\multicolumn{8}{l}{\\footnotesize $^\\star$ Selected optimal configuration for final production training and degradation evaluation.} \\\\\n")
        f.write("\\end{tabular}\n")
        f.write("\\end{table}\n")

    logger.info(f"Generated {out_file.name}")
    return out_file


def generate_degradation_table() -> Path:
    """Generates degradation_table.tex comparing test performance across all 6 conditions."""
    csv_path = RESULTS_DIR / "degradation_results.csv"
    df = pd.read_csv(csv_path)
    test_df = df[df["split"] == "test"].copy()

    conditions = ["normal", "noisy_acc", "noisy_gyro", "missing_acc", "missing_gyro", "noisy_both"]
    cond_display = {
        "normal": "Pristine (Normal)",
        "noisy_acc": "Noisy Accel ($\\sigma=0.5$)",
        "noisy_gyro": "Noisy Gyro ($\\sigma=0.5$)",
        "missing_acc": "Missing Accel ($m_{\\text{acc}}=0$)",
        "missing_gyro": "Missing Gyro ($m_{\\text{gyro}}=0$)",
        "noisy_both": "Noisy Both ($\\sigma=1.0$)",
    }

    out_file = TABLES_DIR / "degradation_table.tex"
    with open(out_file, "w", encoding="utf-8") as f:
        f.write("% Auto-generated by src/generate_latex_tables.py - DO NOT EDIT MANUALLY\n")
        f.write("\\begin{table}[htbp]\n")
        f.write("\\centering\n")
        f.write("\\small\n")
        f.write("\\caption{Test Set Classification Performance under Physical Sensor Degradation Conditions ($N=4,613$)}\n")
        f.write("\\label{tab:degradation_results}\n")
        f.write("\\begin{tabular}{lcccccc}\n")
        f.write("\\toprule\n")
        f.write("& \\multicolumn{3}{c}{\\textbf{Test Accuracy (\\%)}} & \\multicolumn{3}{c}{\\textbf{Macro F1 Score}} \\\\\n")
        f.write("\\cmidrule(lr){2-4} \\cmidrule(lr){5-7}\n")
        f.write("\\textbf{Degradation Condition} & \\textbf{Baseline} & \\textbf{Adaptive} & $\\Delta$ \\textbf{Acc} & \\textbf{Baseline} & \\textbf{Adaptive} & $\\Delta$ \\textbf{F1} \\\\\n")
        f.write("\\midrule\n")

        for mode, mode_title in [
            ("trained_on_normal", "\\textit{Training Mode: Clean Normal Data (Pure Robustness)}"),
            ("degradation_aware", "\\textit{Training Mode: Robust Augmentation (Degradation-Aware)}"),
        ]:
            f.write(f"\\multicolumn{{7}}{{l}}{{{mode_title}}} \\\\\n")
            sub = test_df[test_df["training_mode"] == mode]

            for cond in conditions:
                b_row = sub[(sub["model"] == "baseline") & (sub["condition"] == cond)]
                a_row = sub[(sub["model"] == "adaptive") & (sub["condition"] == cond)]

                if not b_row.empty and not a_row.empty:
                    b_acc = float(b_row["accuracy"].iloc[0]) * 100.0
                    a_acc = float(a_row["accuracy"].iloc[0]) * 100.0
                    d_acc = a_acc - b_acc

                    b_f1 = float(b_row["f1_macro"].iloc[0])
                    a_f1 = float(a_row["f1_macro"].iloc[0])
                    d_f1 = a_f1 - b_f1

                    # Bold the better model
                    if abs(d_acc) < 0.1:
                        acc_b_str = f"{b_acc:.2f}\\%"
                        acc_a_str = f"{a_acc:.2f}\\%"
                    elif d_acc > 0:
                        acc_b_str = f"{b_acc:.2f}\\%"
                        acc_a_str = f"\\textbf{{{a_acc:.2f}\\%}}"
                    else:
                        acc_b_str = f"\\textbf{{{b_acc:.2f}\\%}}"
                        acc_a_str = f"{a_acc:.2f}\\%"

                    if abs(d_f1) < 0.001:
                        f1_b_str = f"{b_f1:.4f}"
                        f1_a_str = f"{a_f1:.4f}"
                    elif d_f1 > 0:
                        f1_b_str = f"{b_f1:.4f}"
                        f1_a_str = f"\\textbf{{{a_f1:.4f}}}"
                    else:
                        f1_b_str = f"\\textbf{{{b_f1:.4f}}}"
                        f1_a_str = f"{a_f1:.4f}"

                    sign_acc = "+" if d_acc > 0 else ""
                    sign_f1 = "+" if d_f1 > 0 else ""

                    f.write(
                        f"\\quad {cond_display[cond]} & {acc_b_str} & {acc_a_str} & {sign_acc}{d_acc:.2f}\\% & "
                        f"{f1_b_str} & {f1_a_str} & {sign_f1}{d_f1:.4f} \\\\\n"
                    )

            if mode == "trained_on_normal":
                f.write("\\midrule\n")

        f.write("\\bottomrule\n")
        f.write("\\end{tabular}\n")
        f.write("\\end{table}\n")

    logger.info(f"Generated {out_file.name}")
    return out_file


def generate_weights_table() -> Path:
    """Generates weights_table.tex showing dynamic fusion weight shifts per condition."""
    csv_path = RESULTS_DIR / "adaptive_fusion_weights.csv"
    df = pd.read_csv(csv_path)

    conditions = ["normal", "noisy_acc", "noisy_gyro", "missing_acc", "missing_gyro", "noisy_both"]
    cond_display = {
        "normal": "Pristine (Normal)",
        "noisy_acc": "Noisy Accel ($\\sigma=0.5$)",
        "noisy_gyro": "Noisy Gyro ($\\sigma=0.5$)",
        "missing_acc": "Missing Accel ($m_{\\text{acc}}=0$)",
        "missing_gyro": "Missing Gyro ($m_{\\text{gyro}}=0$)",
        "noisy_both": "Noisy Both ($\\sigma=1.0$)",
    }

    out_file = TABLES_DIR / "weights_table.tex"
    with open(out_file, "w", encoding="utf-8") as f:
        f.write("% Auto-generated by src/generate_latex_tables.py - DO NOT EDIT MANUALLY\n")
        f.write("\\begin{table}[htbp]\n")
        f.write("\\centering\n")
        f.write("\\small\n")
        f.write("\\caption{Adaptive Fusion Module Dynamic Branch Weights ($w_{\\text{acc}}, w_{\\text{gyro}}$) on Test Split}\n")
        f.write("\\label{tab:adaptive_weights_summary}\n")
        f.write("\\begin{tabular}{llccc}\n")
        f.write("\\toprule\n")
        f.write("\\textbf{Training Mode} & \\textbf{Degradation Condition} & \\textbf{Mean} $w_{\\text{acc}}$ ($\\pm$ SD) & \\textbf{Mean} $w_{\\text{gyro}}$ ($\\pm$ SD) & \\textbf{Physical Shift Behavior} \\\\\n")
        f.write("\\midrule\n")

        for mode, mode_label in [
            ("trained_on_normal", "Clean (Normal)"),
            ("degradation_aware", "Robust (Augmented)"),
        ]:
            sub = df[df["training_mode"] == mode]
            for idx, cond in enumerate(conditions):
                row = sub[sub["condition"] == cond]
                if not row.empty:
                    w_a_m = float(row["w_acc_mean"].iloc[0])
                    w_a_s = float(row["w_acc_std"].iloc[0])
                    w_g_m = float(row["w_gyro_mean"].iloc[0])
                    w_g_s = float(row["w_gyro_std"].iloc[0])

                    if w_a_m < 0.05 and w_g_m > 0.95:
                        behavior = "100\\% shift to Gyroscope"
                    elif w_g_m < 0.05 and w_a_m > 0.95:
                        behavior = "100\\% shift to Accelerometer"
                    elif abs(w_a_m - w_g_m) < 0.05:
                        behavior = "Balanced multi-modal reliance"
                    elif w_a_m > w_g_m:
                        behavior = "Primary reliance on Accelerometer"
                    else:
                        behavior = "Primary reliance on Gyroscope"

                    mode_str = f"\\textbf{{{mode_label}}}" if idx == 0 else ""
                    f.write(
                        f"{mode_str} & {cond_display[cond]} & {w_a_m:.4f} ($\\pm {w_a_s:.3f}$) & "
                        f"{w_g_m:.4f} ($\\pm {w_g_s:.3f}$) & {behavior} \\\\\n"
                    )

            if mode == "trained_on_normal":
                f.write("\\midrule\n")

        f.write("\\bottomrule\n")
        f.write("\\end{tabular}\n")
        f.write("\\end{table}\n")

    logger.info(f"Generated {out_file.name}")
    return out_file


def main() -> None:
    TABLES_DIR.mkdir(parents=True, exist_ok=True)
    logger.info("Generating LaTeX tables from real CSV and JSON outputs...")

    generate_split_table()
    generate_hparam_table()
    generate_degradation_table()
    generate_weights_table()

    logger.info("All LaTeX tables successfully created in Reports/tables/.")


if __name__ == "__main__":
    main()
